/**
 * CTA 是话语的按钮形态 —— 拆解与评估的那一句话 (技术方案 §5.3 A6.1 ①).
 *
 * 这几行字是**发给 agent 的原话**，不是模板、不是参数编组：按下 ⚡ 拆解，等价于
 * 在私语里打出下面这一句并按发送。规格把这一条钉死过：
 *
 * > 按钮提交 = 向 agent 发一条 canonical 话语 turn，**无独立 RPC 路径**——执行
 * > 入口统一律的机械保证；**该 turn 落点 = 操作者私语域**。
 *
 * 所以这里只有字符串，没有第二条通道。哪天有人想给拆解加一个「专用接口」，得先
 * 把这段注释删掉——那时他会知道自己在拆的是什么。
 *
 * 三句话的讲究各不相同，都是被 agent 那头的工具反过来定的：
 *
 * - **拆解**要说清「逐条列出做什么、谁做、什么时候前」——提案卡是逐条裁决的，
 *   一句笼统的「帮我拆一下」换回来的是一段散文，没法一条条确认。
 * - **三句都带上 `goalRef`**：成功标准住在云之家那份文档的正文里，而**哪一份
 *   文档**是 agent 唯一推导不出来的东西（4h② 之后评估是回正文读标准的；拆解
 *   备料的第一步同样是读真身正文）。名字不够——两个目标重名时，靠名字找到的
 *   那一份是碰运气找到的。
 * - **重估**要明说「以现在这版」：这颗按钮只在真身改过之后才出现，它存在的全部
 *   理由就是让这一次对账用**新基准**，而不是照着手上那份可能过期的副本。
 *
 * 都不写「请」「麻烦」「尽快」——语气是说话的人自己的事，这三句是他按下按钮时
 * 说出口的话，不是我们替他排的客套。
 */

/** ⚡ 拆解：agent 只有提议权，每条都要过人的手，所以要的是**可逐条裁决**的清单。 */
export function breakdownAsk(goalName: string, goalRef: string): string {
  return `帮我把目标「${goalName}」（${goalRef}）拆成子承诺，逐条列出做什么、谁做、什么时候前。`
}

/**
 * ✓ 评估：差距简报的那一问。
 *
 * `goalRef` 跟着走，因为标准在真身正文里——不给引用，agent 只能拿手上那份副本
 * 对账，而那份副本恰恰是可能已经过时的那一份。
 */
export function assessAsk(goalName: string, goalRef: string): string {
  return `评估目标「${goalName}」（${goalRef}）的完成度，逐条对着成功标准给证据。`
}

/** 以新基准重估：真身改过之后的那一次对账，判据是**现在这版**正文。 */
export function rebaseAsk(goalName: string, goalRef: string): string {
  return `真身正文改过了。以现在这版成功标准，重新评估目标「${goalName}」（${goalRef}）的完成度。`
}

/* ───────────────── 起头：按钮只摆主语，句子是人的 ───────────────── */

/**
 * 下面这几句和上面三句**是两类东西**，分界线值得写下来。
 *
 * 上面三句**完整**：按下就等于说出口，因为那句话完全由按钮决定，人没有可添的内容，
 * 落点也由规则定死（私语域）。下面这几句**故意不完整**：它们里头有一块是人的——
 * 他要问什么、他心里那个目标是什么、会前那一刀要派谁去干——所以按钮只把他送到该
 * 说话的地方并摆好主语，补完和按发送都是他自己的动作。
 *
 * 混掉这条线，两个方向都会出错：把完整句做成起头，是让人替按钮按一次发送（纯损耗
 * 的摩擦）；把起头做成完整句，是替人把话说了（拿走的是主权）。
 */

/**
 * 🔍 问这个目标 —— 问题是提问的人自己的。
 */
export function goalQuestionSeed(goalName: string): string {
  return `关于目标「${goalName}」，我想问：`
}

/**
 * ＋ 委派 —— 派什么、派给谁、什么时候前，全是他要说的。
 *
 * 句子本身不带触发词：**受话**是另一件事，由 composer 那一头按这个部署的触发词补上
 * （只有它知道这里的 agent 叫什么）。这里管的是句子，不是收件人。
 */
export function delegateSeed(goalName: string): string {
  return `关于目标「${goalName}」：`
}

/**
 * 登记他人承诺的**句式骨架** —— 委派五步③ (v4.21+).
 *
 * 骨架，不是稿子。规格把这条单独钉出来过：「预填**话语骨架**（受话人 + 登记句式模板
 * ——**任务内容由人说，agent 不发明委派内容**；demo 为演示流畅预填了示例内容，实现
 * 勿照抄）」。所以这里只有句式和那个人的名字，要做什么、什么时候前是两个**空**。
 *
 * 空写成〔…〕而不是一句像样的示例：一句像样的示例会被原样发出去，而那句话是我们编的，
 * 落库之后却挂在他名下。空看着不完整——它就该看着不完整。
 */
export function registerSeed(name: string): string {
  return `登记承诺：〔要做什么〕，${name}负责，〔什么时候前〕。`
}

/** 为此会准备 —— 会前那一刀要补什么，只有他知道。 */
export function eventPrepSeed(title: string): string {
  return `为「${title}」准备：`
}

/**
 * 差距 → 委派 —— 评估喂回执行，同一个传送门。
 *
 * 板和目标页画的是同一份查询的两级缩放，所以这一句必须只有一份：它们曾经各写各的
 * （一边带着目标名和「还缺的这块」，另一边只丢出一条光秃秃的标准原文），而**两级
 * 缩放各说各话**恰恰是目标页存在时最先长出来的那种裂缝。
 */
export function gapSeed(goalName: string, criterion: string): string {
  return `关于目标「${goalName}」还缺的这块：${criterion}。`
}

/**
 * 🤝 先和 agent 磨一磨 —— **作者权 ≠ 思考伙伴** (v4.10).
 *
 * 磨稿是一次对话，不是一次任务：起头里那块「我想立个什么」是人的，磨点在**怎么算
 * 完成**。所以这一句把方向摆好（追问可验收、磨完递提案），把内容留给他。
 *
 * 「递提案给我签发」这半句不能省：**人签发**是铁律，agent 只有提议权——一句含糊的
 * 「帮我把目标定下来」是在请它越权。
 */
export function goalCraftSeed(what: string): string {
  const said = what.trim()
  return said === ''
    ? '我想立一个目标，先和你磨一磨——追问我怎么算完成，磨到可验收了再递提案给我签发。我想做的是：'
    : `我想立一个目标：${said}。先和你磨一磨——追问我怎么算完成，磨到可验收了再递提案给我签发。`
}
